import { readFile, writeFile, mkdir, cp, chmod } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeSourceDigest } from './source-digest.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist/echo-menu-lyrics');
const app = path.join(out, 'bin/EchoMenuLyrics.app');
const manifest = JSON.parse(await readFile(path.join(root, 'plugin/manifest.json'), 'utf8'));
const sourceDigest = await computeSourceDigest(root);
await mkdir(path.join(app, 'Contents/MacOS'), { recursive: true });
await mkdir(path.join(root, '.build'), { recursive: true });
const style = await readFile(path.join(root, 'plugin/ui/settings.css'), 'utf8');
const client = await readFile(path.join(root, 'plugin/ui/settings.js'), 'utf8');
const page = (await readFile(path.join(root, 'plugin/ui/settings.html'), 'utf8')).replace('/*__STYLE__*/', style).replace('/*__SCRIPT__*/', client);
let entry = '// Generated by scripts/build.mjs. Edit plugin/src and plugin/ui instead.\n' + `const SETTINGS_PAGE_HTML = ${JSON.stringify(page)};\n`;
for (const name of ['core', 'filters', 'settings', 'index']) {
  let source = await readFile(path.join(root, `plugin/src/${name}.js`), 'utf8');
  source = source.replace(/^import .+;\r?\n/gm, '').replace(/^export /gm, '');
  entry += '\n' + source;
}
entry += '\nexport { activate, deactivate };\n';
await writeFile(path.join(out, 'index.js'), entry);
await cp(path.join(root, 'plugin/manifest.json'), path.join(out, 'manifest.json'));
await cp(path.join(root, 'plugin/icon.svg'), path.join(out, 'icon.svg'));
if (process.argv.includes('--js-only')) { console.log(`Updated plugin entry: ${out}`); process.exit(0); }
const buildInfo = path.join(root, '.build/BuildInfo.swift');
await writeFile(buildInfo, `let buildSourceDigest = ${JSON.stringify(sourceDigest)}\nlet buildVersion = ${JSON.stringify(manifest.version)}\n`);
const sources = [buildInfo, ...['Model', 'Connection', 'LyricView', 'Layout', 'MenuController', 'main'].map(name => path.join(root, `native/${name}.swift`))];
function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status || 1);
}
const architectures = process.argv.includes('--universal') ? ['arm64', 'x86_64'] : [process.arch === 'arm64' ? 'arm64' : 'x86_64'];
for (const arch of architectures) {
  run('xcrun', ['swiftc', '-swift-version', '5', '-O', '-target', `${arch}-apple-macosx13.0`,
    '-module-cache-path', path.join(root, '.build/module-cache'), ...sources,
    '-framework', 'AppKit', '-framework', 'WebKit', '-framework', 'CoreText', '-framework', 'ApplicationServices',
    '-o', path.join(root, `.build/EchoMenuLyrics-${arch}`)]);
}
const executable = path.join(app, 'Contents/MacOS/EchoMenuLyrics');
if (architectures.length > 1) run('lipo', ['-create', ...architectures.map(arch => path.join(root, `.build/EchoMenuLyrics-${arch}`)), '-output', executable]);
else await cp(path.join(root, `.build/EchoMenuLyrics-${architectures[0]}`), executable);
await chmod(executable, 0o755);
await writeFile(path.join(app, 'Contents/Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>cc.echo.menu-lyrics</string>
<key>CFBundleName</key><string>EchoMenuLyrics</string>
<key>CFBundleDisplayName</key><string>EchoMusic 菜单栏歌词</string>
<key>CFBundleExecutable</key><string>EchoMenuLyrics</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleShortVersionString</key><string>${manifest.version}</string>
<key>CFBundleVersion</key><string>8</string>
<key>EchoMenuLyricsSourceDigest</key><string>${sourceDigest}</string>
<key>LSMinimumSystemVersion</key><string>13.0</string>
<key>LSUIElement</key><true/>
<key>NSHighResolutionCapable</key><true/>
</dict></plist>\n`);
run('codesign', ['--force', '--sign', '-', app]);
run(executable, ['--self-test']);
console.log(`Built ${out} (${architectures.join(', ')})`);
